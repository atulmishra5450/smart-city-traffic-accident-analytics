# ?????????????????????????????????????????????????????????????????????????????
# TEST 7 ? One-Way ANOVA: Congestion by Weather Condition
# ?????????????????????????????????????????????????????????????????????????????
def test_weather_vs_congestion_anova(df):
    separator("TEST 7: Weather Condition vs Congestion Level (ANOVA)")
    groups = [g["Congestion_Level_%"].dropna().values
              for _, g in df.groupby("Weather")]
    f_stat, p = stats.f_oneway(*groups)
    print(f"H0: Mean congestion level is equal across all weather conditions")
    print(f"H1: At least one weather condition has a different mean congestion")
    print(f"F = {f_stat:.2f}  |  p-value = {p:.4e}")
    if p < ALPHA:
        print(f">> REJECT H0 ? congestion levels differ significantly across weather types.")
        print(f"  Rain, Fog, and Storm are associated with higher congestion.")
    else:
        print(f">> FAIL to reject H0.")


# ?????????????????????????????????????????????????????????????????????????????
# TEST 8 ? Independent t-test: Accident severity score, peak vs off-peak
# ?????????????????????????????????????????????????????????????????????????????
def test_peak_vs_offpeak_severity(df):
    separator("TEST 8: Peak Hours vs Off-Peak ? Severity Score (t-test)")
    acc = df[df["Accident_Flag"] == 1]
    peak    = acc[acc["Peak_Hour_Flag"] == 1]["Severity_Score"].dropna()
    offpeak = acc[acc["Peak_Hour_Flag"] == 0]["Severity_Score"].dropna()
    t_stat, p = stats.ttest_ind(peak, offpeak, equal_var=False)  # Welch's t-test
    print(f"H0: Mean accident severity score is the same during peak and off-peak hours")
    print(f"H1: Accident severity differs between peak and off-peak hours")
    print(f"Peak mean:    {peak.mean():.4f}")
    print(f"Off-peak mean:{offpeak.mean():.4f}")
    print(f"Welch's t = {t_stat:.4f}  |  p-value = {p:.4e}")
    if p < ALPHA:
        print(f">> REJECT H0 ? severity scores differ between peak and off-peak.")
    else:
        print(f">> FAIL to reject H0 ? no significant severity difference.")
        print(f"  Accidents are equally severe regardless of time of day.")


